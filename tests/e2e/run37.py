import asyncio, os
HERE=os.path.dirname(os.path.abspath(__file__))
APP='file://'+os.path.abspath(os.path.join(HERE,'..','..','index.html'))
CHROME=os.environ.get('CHROME_PATH') or None
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=CHROME, args=['--no-sandbox'])
        pg = await b.new_page(viewport={'width':1400,'height':1000}); errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.add_init_script("window.__NO_TERMS=true")
        async def route(r):
            u=r.request.url
            if 'supabase' in u and u.endswith('.js'): await r.fulfill(path=os.path.join(HERE,'fake-supabase.js'), content_type='application/javascript')
            elif u.startswith('file://'): await r.continue_()
            else: await r.abort()
        await pg.route('**/*', route)
        async def yes():
            await pg.wait_for_timeout(300)
            if await pg.query_selector('.dj-ask [data-ask="yes"]'): await pg.click('.dj-ask [data-ask="yes"]'); await pg.wait_for_timeout(500)
        def statuses(): return pg.eval_on_selector_all('#chgTable tbody tr[data-row]','e=>e.map(r=>r.querySelector("b").textContent+":"+r.querySelector(".chg-pill").textContent)')
        await pg.goto(APP); await pg.wait_for_timeout(900)
        await pg.click('.nav-btn[data-view="interest"]'); await pg.wait_for_timeout(700)
        print('start tab', await pg.eval_on_selector('[data-chgtab].active','e=>e.textContent'))
        await pg.click('[data-chgtab="invoices"]'); await pg.wait_for_timeout(300)
        print('no terms', await statuses())
        print('banner', (await pg.inner_text('#chgBanner'))[:140])
        await pg.click('[data-chgtab="terms"]'); await pg.wait_for_timeout(300)
        print('rules locked', await pg.inner_text('#chgRulesLocked'))
        await pg.set_input_files('#termsFile', files=[{'name':'Acme_Terms.pdf','mimeType':'application/pdf','buffer':b'%PDF-1.4'}]); await pg.wait_for_timeout(1300)
        print('limits form', await pg.evaluate("[document.querySelector('[data-lk=\"interest.rate_pct\"]').value, document.querySelector('[data-lk=\"interest.start\"]').value, [...document.querySelectorAll('[data-lf]')].map(r=>r.querySelector('[data-lf-k=name]').value+':'+r.querySelector('[data-lf-k=max_amount]').value+':'+r.querySelector('[data-lf-k=min_after_days]').value).join(',')]"))
        print('manual', (await pg.inner_text('#termsLimits .lim-manual')).replace('\n',' | ')[:200])
        await pg.screenshot(path='t37_limits.png', full_page=True)
        await pg.click('[data-lim="confirm"]'); await pg.wait_for_timeout(300)
        await pg.check('[data-lk="checked"]'); await pg.click('[data-lim="confirm"]'); await pg.wait_for_timeout(900)
        print('confirmed view', (await pg.inner_text('#termsLimits')).replace('\n',' | ')[:260])
        print('rules form', await pg.evaluate("[document.getElementById('chgRulesBody').hidden, document.getElementById('chgRate').value, document.getElementById('chgStart').value, [...document.querySelectorAll('#chgFees [data-f=name]')].map(x=>x.value).join(',')]"))
        await pg.fill('#chgRate','15'); await pg.click('#chgSaveBtn'); await pg.wait_for_timeout(400)
        print('over limit dialog', (await pg.inner_text('.dj-ask'))[:200].replace('\n',' | ') if await pg.query_selector('.dj-ask') else None)
        await yes()
        await pg.fill('#chgRate','11'); await pg.click('#chgSaveBtn'); await pg.wait_for_timeout(800)
        print('saved rules', await pg.evaluate("JSON.stringify(window.__DB.org_terms_documents[0].rules).slice(0,160)"))
        await pg.click('[data-chgtab="invoices"]'); await pg.wait_for_timeout(300)
        print('confirmed, no acceptance', await statuses())
        await pg.click('[data-chgtab="terms"]'); await pg.wait_for_timeout(300)
        await pg.click('[data-acc="new"]'); await pg.wait_for_timeout(200)
        await pg.fill('[data-ak="accepted_on"]','2026-07-01')
        await pg.check('.acc-pick label:has-text("Bluestone") input')
        await pg.set_input_files('[data-ak-file]', files=[{'name':'Signed application.pdf','mimeType':'application/pdf','buffer':b'%PDF'}]); await pg.wait_for_timeout(200)
        await pg.click('[data-acc="save"]'); await pg.wait_for_timeout(900)
        print('acceptances', await pg.evaluate("window.__DB.terms_acceptances.map(a=>a.debtor_id+':'+a.accepted_on)"))
        print('who', (await pg.inner_text('#termsWho')).replace('\n',' | ')[:200])
        await pg.screenshot(path='t37_terms.png', full_page=True)
        await pg.click('[data-chgtab="invoices"]'); await pg.wait_for_timeout(400)
        print('after acceptance', await statuses())
        await pg.select_option('#chgFilter','noterms'); await pg.wait_for_timeout(200)
        print('filter no terms', await statuses())
        await pg.select_option('#chgFilter','all'); await pg.wait_for_timeout(200)
        await pg.screenshot(path='t37_inv.png', full_page=True)
        await pg.click('[data-chgtab="calc"]'); await pg.wait_for_timeout(300)
        print('calc', (await pg.inner_text('#calcOut')).replace('\n',' | ')[:160])
        await pg.click('.nav-btn[data-view="dashboard"]'); await pg.wait_for_timeout(400)
        await pg.click('.nav-btn[data-view="statements"]'); await pg.wait_for_timeout(600)
        print(errs); await b.close()
asyncio.run(main())
