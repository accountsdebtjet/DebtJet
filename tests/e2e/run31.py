import asyncio, os
HERE=os.path.dirname(os.path.abspath(__file__))
APP='file://'+os.path.abspath(os.path.join(HERE,'..','..','index.html'))
CHROME=os.environ.get('CHROME_PATH') or None
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=CHROME, args=['--no-sandbox'])
        pg = await b.new_page(viewport={'width':1400,'height':1000}); errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('dialog', lambda d: asyncio.ensure_future(d.accept()))
        async def route(r):
            u=r.request.url
            if 'supabase' in u and u.endswith('.js'): await r.fulfill(path=os.path.join(HERE,'fake-supabase.js'), content_type='application/javascript')
            elif u.startswith('file://'): await r.continue_()
            else: await r.abort()
        await pg.route('**/*', route)
        await pg.goto(APP); await pg.wait_for_timeout(800)
        await pg.click('.nav-btn[data-view="recovery"]'); await pg.wait_for_timeout(900)
        pg.on('dialog', lambda d: asyncio.ensure_future(d.accept()))
        await pg.evaluate("""Object.assign(window.__DB.debtors[0], {legal_name:'BLUESTONE LEGAL PTY LTD', acn:'004085616', abn:'53004085616', abn_status:'Active', address_line1:'Level 4, 120 Edward St', suburb:'Brisbane', state:'QLD', postcode:'4000', debtor_kind:'company'})""")
        await pg.click('.nav-btn[data-view="dashboard"]'); await pg.wait_for_timeout(600)
        await pg.screenshot(path='c_dash.png')
        await pg.click('.nav-btn[data-view="letters"]'); await pg.wait_for_timeout(900)
        await pg.click('#ldCaseCard [data-ltab-go="letter"]'); await pg.wait_for_timeout(900)
        print('ins hidden', await pg.eval_on_selector('#insPanel','e=>e.hidden'), 'dock hidden', await pg.eval_on_selector('#styleDock','e=>e.hidden'))
        await pg.screenshot(path='c_letter.png')
        await pg.select_option('#styleDock [data-dock="font_size"]', '13'); await pg.wait_for_timeout(400)
        await pg.click('#styleDock [data-sch-open]'); await pg.click('#styleDock [data-sch="4"]'); await pg.wait_for_timeout(400)
        print('paper font size', await pg.eval_on_selector('#letterPaper .ld','e=>getComputedStyle(e).fontSize'))
        await pg.click('#insPanel [data-instab="fields"]'); await pg.wait_for_timeout(200)
        ed = await pg.query_selector('#letterPaper .dj-txt[data-ldb]'); await ed.click(); await pg.keyboard.press('End')
        await pg.click('#insPanel [data-insfield="pay_by_date"]'); await pg.wait_for_timeout(300)
        print('chip inserted', await pg.eval_on_selector_all('#letterPaper [data-var="pay_by_date"]','e=>e.length'))
        await pg.click('.nav-btn[data-view="statements"]'); await pg.wait_for_timeout(900)
        await pg.screenshot(path='c_stmt.png')
        print('stmt ins', await pg.eval_on_selector('#insPanel','e=>!e.hidden'), await pg.inner_text('#insPanel .ins-target'))
        await pg.click('.nav-btn[data-view="interest"]'); await pg.wait_for_timeout(700)
        print('interest ins hidden', await pg.eval_on_selector('#insPanel','e=>e.hidden'), 'toggle shown', await pg.eval_on_selector('#tbIns','e=>!e.hidden'))
        print('edge', await pg.eval_on_selector('#edgeR','e=>[e.hidden, JSON.stringify(e.getBoundingClientRect())]'), await pg.evaluate("document.elementFromPoint(1396,500).id || document.elementFromPoint(1396,500).className"))
        await pg.mouse.move(1300, 500); await pg.mouse.move(1396, 500, steps=5); await pg.wait_for_timeout(700)
        print('peek', await pg.eval_on_selector('#insPanel','e=>!e.hidden && e.classList.contains("peek")'))
        await pg.screenshot(path='c_interest_peek.png')
        await pg.mouse.move(600, 500); await pg.wait_for_timeout(900)
        print('after leave hidden', await pg.eval_on_selector('#insPanel','e=>e.hidden'))
        await pg.click('.nav-btn[data-view="recovery"]'); await pg.wait_for_timeout(900)
        await pg.click('[data-rtab-btn="claim"]'); await pg.wait_for_timeout(500)
        btn = await pg.query_selector('#recStartBtn')
        if btn and not await btn.is_disabled(): await btn.click(); await pg.wait_for_timeout(1000)
        await pg.screenshot(path='c_rec.png')
        await pg.emulate_media(color_scheme='dark'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='c_rec_dark.png')
        print(errs); await b.close()
asyncio.run(main())
